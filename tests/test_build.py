"""Fast, lightweight assertions for skill packages and static site artifacts."""
import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"


def test_svg_templates():
    svg_path = ROOT / "skill/templates/poster-template.svg"
    assert svg_path.is_file(), f"Missing template: {svg_path}"
    tree = ET.parse(svg_path)
    root = tree.getroot()
    assert "svg" in root.tag.lower(), "Root element must be svg"


def test_catalog_structure():
    catalog_path = ROOT / "data/catalog.json"
    assert catalog_path.is_file(), f"Missing catalog: {catalog_path}"
    data = json.loads(catalog_path.read_text(encoding="utf-8"))
    assert "titles" in data and len(data["titles"]) > 0
    assert "chapters" in data and len(data["chapters"]) > 0


def test_build_artifacts(site: bool = False):
    # Verify single-page output
    index_html = ROOT / "index.html"
    assert index_html.is_file(), "index.html should be generated by build.py"
    html_content = index_html.read_text(encoding="utf-8")
    assert 'id="study"' in html_content
    assert "font-family:Shan" in html_content

    # If --site was specified or _site directory exists, verify site output
    if site:
        site_index = ROOT / "_site/index.html"
        assert site_index.is_file(), "_site/index.html should exist when --site is enabled"

    # Verify agent skill zip package
    skill_zip_path = DIST / "omnipotent-youth-society-design.zip"
    assert skill_zip_path.is_file(), f"Missing archive: {skill_zip_path}"
    assert skill_zip_path.stat().st_size > 10_000, "Skill zip package is suspiciously small"

    with zipfile.ZipFile(skill_zip_path, "r") as zf:
        namelist = zf.namelist()
        required_entries = [
            "omnipotent-youth-society-design/SKILL.md",
            "omnipotent-youth-society-design/assets/icon.png",
            "omnipotent-youth-society-design/references/DESIGN.md",
            "omnipotent-youth-society-design/references/SOURCES.md",
            "omnipotent-youth-society-design/templates/poster-template.svg",
            "omnipotent-youth-society-design/templates/workflow.sh",
        ]
        for entry in required_entries:
            assert entry in namelist, f"Missing required file in skill package: {entry}"

    # Verify design kit zip package
    kit_zip_path = DIST / "omnipotent-youth-society-design-kit.zip"
    assert kit_zip_path.is_file(), f"Missing archive: {kit_zip_path}"
    assert kit_zip_path.stat().st_size > 100_000, "Kit zip package is suspiciously small"

    with zipfile.ZipFile(kit_zip_path, "r") as zf:
        kit_namelist = zf.namelist()
        assert "index.html" in kit_namelist
        assert "DESIGN.md" in kit_namelist
        assert "research/SOURCES.md" in kit_namelist


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site", action="store_true", help="Assert that _site/ was generated and valid")
    args = parser.parse_args()

    print("[*] Running lightweight build artifact assertions...")
    test_svg_templates()
    print("    ✓ SVG template XML structure valid")
    test_catalog_structure()
    print("    ✓ Catalog JSON schema valid")
    test_build_artifacts(site=args.site)
    print("    ✓ Offline index.html, dist archives, and structural integrity verified")
    print("\n[SUCCESS] All lightweight build assertions passed!")
